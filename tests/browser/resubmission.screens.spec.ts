import { expect, test, type Page } from '@playwright/test'
import { loseNextWriteCompletion } from './storage-faults'

test.describe.configure({ mode: 'parallel' })

async function start(page: Page, language: 'ar' | 'en' = 'en') {
  await page.goto('/applications/RIFD-2026-004/corrections/current')
  await expect(page.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 60_000 })
  if (await page.locator('html').getAttribute('lang') !== language) await page.getByRole('button', { name: language === 'en' ? 'English' : 'العربية', exact: true }).click()
  await page.getByRole('button', { name: language === 'en' ? 'Huda Ali' : 'هدى علي', exact: true }).click()
  return page.getByRole('region', { name: language === 'en' ? 'Respond to corrections' : 'الرد على التصحيحات', exact: true })
}

for (const language of ['ar', 'en'] as const) test(`${language} resubmission publishes changed targets and the reviewer separately verifies them`, async ({ page }) => {
  const ar = language === 'ar'
  await page.setViewportSize({ width: ar ? 390 : 1440, height: 950 })
  const editor = await start(page, language)
  await editor.getByRole('button', { name: ar ? 'إعادة تقديم التصحيحات' : 'Resubmit corrections', exact: true }).click()
  await expect(editor.getByRole('alert')).toContainText(ar ? 'تغيير' : 'change')
  await editor.getByRole('textbox').fill(ar ? '٤٥٠٬٠٠٠' : '450000')
  await editor.locator('input[type=file]').setInputFiles({ name: 'DEMO-plan.png', mimeType: 'image/png', buffer: Buffer.from('a different fictional purchase plan') })
  await expect(editor.getByRole('button', { name: ar ? 'معاينة الملف الجاهز' : 'Preview ready file', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: ar ? 'إعادة تقديم التصحيحات' : 'Resubmit corrections', exact: true }).click()
  await expect(page).toHaveURL(/\/applications\/RIFD-2026-004$/)
  await expect(page.getByRole('status').filter({ hasText: ar ? 'أُعيد تقديم التصحيحات' : 'Corrections resubmitted' })).toBeVisible()
  await page.getByRole('button', { name: ar ? 'تغيير الهوية' : 'Switch identity', exact: true }).click()
  await page.getByRole('button', { name: ar ? 'سلمى ناصر' : 'Salma Nasser', exact: true }).click()
  await expect(page).toHaveURL(/\/staff\/applications$/)
  await page.goto('/staff/applications/RIFD-2026-004')
  const verification = page.getByRole('heading', { name: ar ? 'التحقق من التصحيحات' : 'Correction verification', exact: true }).locator('..')
  await expect(verification).toContainText(ar ? 'تغير عن المرجع' : 'Changed from baseline')
  await verification.getByRole('button', { name: ar ? 'التحقق من تغيير الحقل' : 'Verify field change', exact: true }).click()
  await expect(verification.getByRole('button', { name: ar ? 'إلغاء التحقق من الحقل' : 'Undo field verification', exact: true })).toBeVisible()
  const documents = page.getByRole('heading', { name: ar ? 'المستندات' : 'Documents', exact: true }).locator('..')
  const plan = documents.getByRole('heading', { name: ar ? 'خطة شراء المخزون' : 'Stock purchase plan', exact: true }).locator('..')
  await plan.getByRole('button', { name: ar ? 'قبول المستند' : 'Accept document', exact: true }).click()
  await expect(verification.getByText(ar ? 'تم التحقق' : 'Verified', { exact: true })).toHaveCount(2)
  if (test.info().project.name === 'chrome') for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 950 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `docs/implementation/evidence/13/review-${language}-${width}.png`, fullPage: true })
  }
})

test('a failed or uncertain resubmission retains prepared evidence and requires outcome inspection', async ({ page }) => {
  const editor = await start(page)
  await editor.getByRole('textbox').fill('450000')
  await editor.locator('input[type=file]').setInputFiles({ name: 'DEMO-retry.png', mimeType: 'image/png', buffer: Buffer.from('fictional resubmit retry') })
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toBeVisible()
  await editor.getByText('Demo controls', { exact: true }).click()
  await editor.getByLabel('Next failure', { exact: true }).selectOption('submission')
  await editor.getByRole('button', { name: 'Resubmit corrections', exact: true }).click()
  await expect(editor.getByRole('alert')).toBeVisible()
  await expect(editor.getByRole('textbox')).toHaveValue('450000')
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toBeVisible()
  await page.evaluate(loseNextWriteCompletion)
  await editor.getByRole('button', { name: 'Resubmit corrections', exact: true }).click()
  await expect(editor.getByRole('button', { name: 'Inspect resubmission outcome', exact: true })).toBeVisible({ timeout: 20_000 })
  await editor.getByRole('button', { name: 'Inspect resubmission outcome', exact: true }).click()
  await expect(page).toHaveURL(/\/applications\/RIFD-2026-004$/)
  await expect(page.getByRole('status').filter({ hasText: 'Corrections resubmitted' })).toBeVisible()
})

test('another request carries an unsuitable plan into a fresh workspace and retains the earlier assessment', async ({ page }) => {
  const editor = await start(page)
  await editor.getByRole('textbox').fill('450000')
  await editor.locator('input[type=file]').setInputFiles({ name: 'DEMO-first.png', mimeType: 'image/png', buffer: Buffer.from('first fictional plan') })
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'Resubmit corrections', exact: true }).click()
  await expect(page).toHaveURL(/\/applications\/RIFD-2026-004$/)
  await page.getByRole('button', { name: 'Switch identity', exact: true }).click()
  await page.getByRole('button', { name: 'Salma Nasser', exact: true }).click()
  await expect(page).toHaveURL(/\/staff\/applications$/)
  await page.goto('/staff/applications/RIFD-2026-004')
  const plan = page.getByRole('heading', { name: 'Stock purchase plan', exact: true }).locator('..')
  await plan.getByRole('button', { name: 'Needs replacement', exact: true }).click()
  await page.getByRole('textbox', { name: 'Replacement reason', exact: true }).fill('The first plan still lacks item costs.')
  await page.getByRole('button', { name: 'Save assessment', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Replacement reason', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Request corrections', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Stock purchase plan', exact: true }).check()
  await page.getByRole('textbox', { name: 'Correction reason: Stock purchase plan', exact: true }).fill('Include the item costs.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and send request', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Correction request sent.' })).toBeVisible()
  await page.getByRole('link', { name: 'Back to review', exact: true }).click()
  await page.getByText('Previous response assessments', { exact: true }).click()
  await expect(page.getByText('The first plan still lacks item costs.', { exact: true }).last()).toBeVisible()
  await page.getByRole('button', { name: 'Switch identity', exact: true }).click()
  await page.getByRole('button', { name: 'Huda Ali', exact: true }).click()
  await expect(page).toHaveURL(/\/applications$/)
  await page.goto('/applications/RIFD-2026-004/corrections/current')
  await expect(editor).toContainText('Include the item costs.')
  await expect(editor.getByRole('textbox')).toHaveCount(0)
  await editor.locator('input[type=file]').setInputFiles({ name: 'DEMO-second.png', mimeType: 'image/png', buffer: Buffer.from('a fictional plan with item costs') })
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'Save progress', exact: true }).click()
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(editor).toContainText('DEMO-second.png', { timeout: 30_000 })
  await editor.getByRole('button', { name: 'Resubmit corrections', exact: true }).click()
  await expect(page).toHaveURL(/\/applications\/RIFD-2026-004$/)
  await expect(page.getByRole('status').filter({ hasText: 'Corrections resubmitted' })).toBeVisible()
  await expect(page.getByText('The first plan still lacks item costs.', { exact: true })).toHaveCount(0)
  await page.goto('/applications/RIFD-2026-004/history')
  const first = page.getByRole('region', { name: 'Published response 1', exact: true })
  const second = page.getByRole('region', { name: 'Published response 2', exact: true })
  await expect(first).toContainText('450,000')
  for (const [round, name] of [[first, 'DEMO-first.png'], [second, 'DEMO-second.png']] as const) {
    await round.getByRole('button', { name: 'Preview published document: Stock purchase plan', exact: true }).click()
    const preview = page.getByRole('dialog')
    await expect(preview).toContainText(name)
    await expect(preview.getByRole('link', { name: 'Download file', exact: true })).toBeVisible()
    await preview.getByRole('button', { name: 'Close preview', exact: true }).click()
  }
})
