  await expect(page.getByRole('link', { name: 'Open application RIFD-2026-011', exact: true })).toBeVisible()
  await page.goto('/staff/applications')
  await expect(page.getByLabel('Assignment filter')).toHaveAttribute('data-value', 'colleague')
  await expect(page.getByLabel('Sort applications')).toHaveAttribute('data-value', 'amountAsc')
  await expect(page.getByRole('searchbox')).toHaveValue('')
  await expect(page.getByText('Page 1 of 1', { exact: true })).toBeVisible()
  await page.goto('/staff/applications?assignment=all&sort=dateAsc&page=99')
  await expect(page.getByText('Page 3 of 3', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Sort applications')).toHaveAttribute('data-value', 'dateAsc')
  await expect(page.getByRole('link', { name: 'Open application RIFD-2026-012', exact: true })).toBeVisible()
  await page.goto('/staff/applications?status=draft&assignment=nobody&sort=invalid&page=-1')
  await expect(page.getByLabel('Assignment filter')).toHaveAttribute('data-value', 'colleague')
  await expect(page.getByLabel('Sort applications')).toHaveAttribute('data-value', 'amountAsc')
