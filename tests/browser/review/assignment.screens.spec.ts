import { expect, test, type Page } from '@playwright/test'
import { loseNextWriteCompletion } from '../support/storage-faults'

test.describe.configure({ mode: 'parallel' })

async function start(page: Page, language: 'ar' | 'en' = 'en', id = '002') {
  await page.goto(`/staff/applications/RIFD-2026-${id}`)
  await expect(page.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 30_000 })
  if (await page.locator('html').getAttribute('lang') !== language) await page.getByRole('button', { name: language === 'en' ? 'English' : 'العربية', exact: true }).click()
  await page.getByRole('button', { name: language === 'en' ? 'Salma Nasser' : 'سلمى ناصر', exact: true }).click()
  await expect(page.getByRole('heading', { name: `RIFD-2026-${id}`, exact: true })).toBeVisible()
}

for (const language of ['ar', 'en'] as const) test(`${language} claim, confirmed transfer, reclaim and explicit review start`, async ({ page }) => {
  await page.setViewportSize({ width: language === 'ar' ? 390 : 1440, height: 950 })
  await start(page, language)
  const ar = language === 'ar'
  const actions = page.getByRole('region', { name: ar ? 'الإسناد والمراجعة' : 'Assignment and review' })
  const claim = actions.getByRole('button', { name: ar ? 'استلام الطلب' : 'Claim application', exact: true })
  await expect(claim).toBeVisible()
  await expect(actions.getByRole('button', { name: ar ? 'بدء المراجعة' : 'Start review', exact: true })).toHaveCount(0)
  await claim.click()
  await expect(actions.getByText(ar ? 'مسند إليك' : 'Assigned to you', { exact: true })).toBeVisible()
  await actions.getByRole('button', { name: ar ? 'إلغاء الإسناد' : 'Unassign application', exact: true }).click()
  await claim.click()
  const transfer = actions.getByRole('button', { name: ar ? 'نقل إلى خالد علي' : 'Transfer to Khaled Ali', exact: true })
  await transfer.click()
  const dialog = page.getByRole('dialog', { name: ar ? 'تأكيد نقل الإسناد' : 'Confirm reviewer transfer' })
  await expect(dialog).toContainText(ar ? 'سلمى ناصر' : 'Salma Nasser')
  await expect(dialog).toContainText(ar ? 'خالد علي' : 'Khaled Ali')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(transfer).toBeFocused()
  await transfer.click()
  await dialog.getByRole('button', { name: ar ? 'تأكيد النقل' : 'Confirm transfer', exact: true }).click()
  await expect(actions.getByRole('button', { name: ar ? 'استرداد من خالد علي' : 'Reclaim from Khaled Ali', exact: true })).toBeVisible()
  await expect(actions.getByRole('button', { name: ar ? 'بدء المراجعة' : 'Start review', exact: true })).toHaveCount(0)
  await actions.getByRole('button', { name: ar ? 'استرداد من خالد علي' : 'Reclaim from Khaled Ali', exact: true }).click()
  await dialog.getByRole('button', { name: ar ? 'تأكيد النقل' : 'Confirm transfer', exact: true }).click()
  await actions.getByRole('button', { name: ar ? 'بدء المراجعة' : 'Start review', exact: true }).click()
  await expect(page.getByText(ar ? 'قيد المراجعة' : 'Under review', { exact: true }).first()).toBeVisible()
  await expect(actions.getByRole('button', { name: ar ? 'إلغاء الإسناد' : 'Unassign application', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByText(ar ? 'قيد المراجعة' : 'Under review', { exact: true }).first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('an uncertain claim requires receipt inspection and preserves readable detail', async ({ page }) => {
  await start(page)
  await page.evaluate(loseNextWriteCompletion)
  const actions = page.getByRole('region', { name: 'Assignment and review' })
  await actions.getByRole('button', { name: 'Claim application', exact: true }).click()
  await expect(actions.getByRole('button', { name: 'Inspect action outcome', exact: true })).toBeVisible({ timeout: 15_000 })
  await expect(actions.getByRole('button', { name: 'Claim application', exact: true })).toBeDisabled()
  await actions.getByRole('button', { name: 'Inspect action outcome', exact: true }).click()
  await expect(actions.getByText('Action completed.', { exact: true })).toBeVisible()
  await expect(actions.getByRole('button', { name: 'Start review', exact: true })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'Submitted information', exact: true })).toBeVisible()
})

test('a shared assignment change invalidates confirmation and refreshes review permissions', async ({ page, context }) => {
  await start(page, 'en', '003')
  const second = await context.newPage()
  await start(second, 'en', '003')
  const actions = page.getByRole('region', { name: 'Assignment and review' })
  const other = second.getByRole('region', { name: 'Assignment and review' })
  await actions.getByRole('button', { name: 'Transfer to Khaled Ali', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await other.getByRole('button', { name: 'Unassign application', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(actions.getByRole('button', { name: 'Claim application', exact: true })).toBeVisible()
  await expect(actions.getByText(/previous confirmation was cleared/)).toBeVisible()
  await actions.getByRole('button', { name: 'Claim application', exact: true }).click()
  await other.getByRole('button', { name: 'Transfer to Khaled Ali', exact: true }).click()
  await second.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await expect(actions.getByRole('button', { name: 'Start review', exact: true })).toHaveCount(0)
  await expect(actions.getByRole('button', { name: 'Reclaim from Khaled Ali', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Submitted information', exact: true })).toBeVisible()
})

test('a missed assignment notice refuses a stale start and requires Load latest before reclaim', async ({ page, context }) => {
  await context.addInitScript(() => {
    BroadcastChannel.prototype.postMessage = () => {}
    const miss = (event: Event) => event.stopImmediatePropagation()
    window.addEventListener('focus', miss, true)
    window.addEventListener('pageshow', miss, true)
    document.addEventListener('visibilitychange', miss, true)
  })
  await start(page, 'en', '003')
  const second = await context.newPage()
  await start(second, 'en', '003')
  await second.getByRole('button', { name: 'Transfer to Khaled Ali', exact: true }).click()
  await second.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await expect(second.getByRole('button', { name: 'Reclaim from Khaled Ali', exact: true })).toBeVisible()
  const actions = page.getByRole('region', { name: 'Assignment and review' })
  await actions.getByRole('button', { name: 'Start review', exact: true }).click()
  await expect(actions.getByRole('alert')).toContainText('The application changed.')
  await expect(actions.getByRole('button', { name: 'Start review', exact: true })).toBeDisabled()
  await actions.getByRole('button', { name: 'Load latest', exact: true }).click()
  await expect(actions.getByRole('button', { name: 'Start review', exact: true })).toHaveCount(0)
  await actions.getByRole('button', { name: 'Reclaim from Khaled Ali', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await actions.getByRole('button', { name: 'Start review', exact: true }).click()
  await expect(page.getByText('Under review', { exact: true }).first()).toBeVisible()
})

