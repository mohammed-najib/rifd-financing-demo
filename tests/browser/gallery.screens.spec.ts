test('the canonical card and button families share hover feedback and honor reduced motion', async ({ page }) => {
  await page.goto('/components')
  await page.getByRole('heading', { name: 'مكونات الواجهة', exact: true }).waitFor({ timeout: 30_000 })
  const cards = page.locator('section[aria-labelledby="gallery-cards"]')
  let shadow = ''
  for (const locator of [cards.locator('.panel').first(), cards.locator('aside.summary'), cards.locator('.draft-feedback'), cards.locator('.identity-card').first(), cards.locator('.application-card').first(), cards.locator('.queue-counts > div').first(), page.locator('.product-card').first()]) {
    await locator.hover()
    await expect.poll(() => locator.evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m42)).toBe(-3)
    const next = await locator.evaluate(element => getComputedStyle(element).boxShadow)
    expect(next).not.toBe('none')
    if (shadow) expect(next).toBe(shadow)
    shadow = next
  }
  const buttons = page.locator('section[aria-labelledby="gallery-buttons"]')
  const back = buttons.getByRole('button', { name: 'رجوع', exact: true })
  const link = buttons.getByRole('link', { name: 'زر رابط', exact: true })
  const appearance = async (locator: typeof back) => {
    await locator.hover()
    await expect.poll(() => locator.evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m42)).toBe(-2)
    return locator.evaluate(element => { const style = getComputedStyle(element); return [style.backgroundColor, style.borderColor, style.boxShadow, style.transitionDuration] })
  }
  expect(await appearance(back)).toEqual(await appearance(link))
  const file = page.locator('#gallery-file')
  await file.hover()
  const picker = page.locator('.file-picker').first()
  await expect(picker).toHaveCSS('border-top-color', 'rgb(11, 100, 88)')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await cards.locator('.identity-card').first().hover()
  await expect.poll(() => cards.locator('.identity-card').first().evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m42)).toBe(0)
  await expect(cards.locator('.identity-card').first()).toHaveCSS('transition-duration', '0s')
  await back.hover()
  await expect(back).toHaveCSS('transform', 'none')
  await expect(back).toHaveCSS('transition-duration', '0s')
  await expect(buttons.locator('.button-spinner')).toHaveCSS('animation-name', 'none')
  await expect(picker).toHaveCSS('transition-duration', '0s')
})
