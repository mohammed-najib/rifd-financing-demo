import { expect, test, type Page } from '@playwright/test'
import { loseNextWriteCompletion } from './storage-faults'

test.describe.configure({ mode: 'parallel' })

async function start(page: Page, language: 'ar' | 'en' = 'en', suffix = '/corrections/current') {
  await page.goto(`/applications/RIFD-2026-004${suffix}`)
  await expect(page.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 60_000 })
  if (await page.locator('html').getAttribute('lang') !== language) await page.getByRole('button', { name: language === 'en' ? 'English' : 'العربية', exact: true }).click()
  await page.getByRole('button', { name: language === 'en' ? 'Huda Ali' : 'هدى علي', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'RIFD-2026-004', exact: true })).toBeVisible()
}

for (const language of ['ar', 'en'] as const) test(`${language} only requested targets are editable and private saved files restore after reload`, async ({ page }) => {
  const ar = language === 'ar'
  await page.setViewportSize({ width: ar ? 390 : 1440, height: 950 })
  await start(page, language)
  const editor = page.getByRole('region', { name: ar ? 'الرد على التصحيحات' : 'Respond to corrections', exact: true })
  await expect(editor).toBeVisible()
  await expect(editor.getByRole('textbox')).toHaveCount(1)
  const amount = editor.getByRole('textbox', { name: ar ? 'مبلغ التمويل' : 'Financing amount', exact: true })
  await expect(amount).toHaveValue('600000')
  await expect(editor.locator('input[type=file]')).toHaveCount(1)
  await expect(editor).toContainText(ar ? 'المعلومات المرجعية عند الطلب' : 'Fixed request baseline')
  if (test.info().project.name === 'chrome') {
    await expect(editor.locator('#purchase-sample')).toBeVisible()
    for (const width of [390, 1440]) {
      await page.setViewportSize({ width, height: 950 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `docs/implementation/evidence/12/response-${language}-${width}.png`, fullPage: true })
    }
  }
  await amount.fill(' invalid ')
  await editor.locator('input[type=file]').setInputFiles({ name: 'DEMO-private.png', mimeType: 'image/png', buffer: Buffer.from('fictional private plan') })
  await expect(editor.getByRole('status').filter({ hasText: ar ? 'جاهز للحفظ' : 'Ready to save' })).toBeVisible()
  await editor.getByRole('button', { name: ar ? 'حفظ التقدم' : 'Save progress', exact: true }).click()
  await expect(editor.getByRole('status').filter({ hasText: ar ? 'محفوظ' : 'Saved' })).toBeVisible()
  await expect(editor.getByRole('button', { name: ar ? 'معاينة الملف المحفوظ' : 'Preview saved file', exact: true })).toBeVisible()
  const submitted = page.getByRole('heading', { name: ar ? 'المعلومات المقدمة' : 'Submitted information', exact: true }).locator('..')
  await expect(submitted).toContainText('600,000')
  await expect(submitted).not.toContainText(' invalid ')
  await page.reload()
  await expect(amount).toHaveValue(' invalid ', { timeout: 30_000 })
  await expect(editor).toContainText('DEMO-private.png')
  await expect(editor.getByRole('button', { name: ar ? 'معاينة الملف الجاهز' : 'Preview ready file', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('failed preparation and saving retain the old file and ready replacement for retry', async ({ page }) => {
  await start(page)
  const editor = page.getByRole('region', { name: 'Respond to corrections', exact: true })
  await editor.getByText('Demo controls', { exact: true }).click()
  await editor.getByLabel('Next failure', { exact: true }).selectOption('upload')
  await editor.locator('input[type=file]').setInputFiles({ name: 'DEMO-retry.png', mimeType: 'image/png', buffer: Buffer.from('retry private bytes') })
  await expect(editor.getByRole('button', { name: 'Retry preparation', exact: true })).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Preview saved file', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'Retry preparation', exact: true }).click()
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toBeVisible()
  await editor.getByRole('textbox', { name: 'Financing amount', exact: true }).fill('450000')
  await editor.getByLabel('Next failure', { exact: true }).selectOption('save')
  await editor.getByRole('button', { name: 'Save progress', exact: true }).click()
  await expect(editor.getByRole('alert')).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toBeVisible()
  await expect(editor.getByRole('textbox', { name: 'Financing amount', exact: true })).toHaveValue('450000')
  await editor.getByRole('button', { name: 'Save progress', exact: true }).click()
  await expect(editor.getByRole('button', { name: 'Preview ready file', exact: true })).toHaveCount(0)
  await expect(editor).toContainText('Saved in correction workspace: DEMO-retry.png')
})

