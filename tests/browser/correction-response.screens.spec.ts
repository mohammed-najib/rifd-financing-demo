test('a dirty correction workspace requires inspection and explicit reapplication after a competing save', async ({ page, context }) => {
  await start(page)
  const amount = page.getByRole('textbox', { name: 'Financing amount', exact: true })
  await amount.fill('400000')
  const second = await context.newPage()
  await start(second)
  await second.getByRole('textbox', { name: 'Financing amount', exact: true }).fill('450000')
  await second.getByRole('button', { name: 'Save progress', exact: true }).click()
  await expect(second.getByRole('region', { name: 'Respond to corrections', exact: true }).getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Inspect latest correction workspace', exact: true })).toBeVisible()
  await expect(amount).toHaveValue('400000')
  await expect(page.getByRole('button', { name: 'Save progress', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Reapply my edits', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Inspect latest correction workspace', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reapply my edits', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reapply my edits', exact: true }).click()
  await page.getByRole('button', { name: 'Save progress', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Respond to corrections', exact: true }).getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible()
  await page.reload()
  await expect(amount).toHaveValue('400000', { timeout: 30_000 })
})

