async function loseNextCompletion(page: Page) {
  // Lose one final commit observation without changing storage behavior.
  await page.evaluate(() => {
    const transaction = IDBDatabase.prototype.transaction
    let loseNext = true
    IDBDatabase.prototype.transaction = function (...args: Parameters<IDBDatabase['transaction']>) {
      const tx = transaction.apply(this, args)
      if (args[1] === 'readwrite' && loseNext) {
        loseNext = false
        Object.defineProperty(tx, 'oncomplete', { configurable: true, set() { /* Lost observation. */ } })
      }
      return tx
    }
  })
}

