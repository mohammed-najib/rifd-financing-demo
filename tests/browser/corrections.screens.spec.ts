import { expect, test, type Page } from '@playwright/test'
import { loseNextWriteCompletion } from './storage-faults'

test.describe.configure({ mode: 'parallel' })
async function start(page: Page, language: 'ar' | 'en' = 'en', id = '007', composer = true) {
  await page.goto(`/staff/applications/RIFD-2026-${id}${composer ? '/correction-request' : ''}`)
  await expect(page.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 30_000 })
  if (await page.locator('html').getAttribute('lang') !== language) await page.getByRole('button', { name: language === 'en' ? 'English' : 'العربية', exact: true }).click()
  await page.getByRole('button', { name: language === 'en' ? 'Salma Nasser' : 'سلمى ناصر', exact: true }).click()
  await expect(page.getByRole('heading', { name: `RIFD-2026-${id}`, exact: true })).toBeVisible()
}

for (const language of ['ar', 'en'] as const) test(`${language} inspect and confirm only the selected field and document, then pause review`, async ({ page }) => {
  const ar = language === 'ar'
  await page.setViewportSize({ width: ar ? 390 : 1440, height: 950 })
  await start(page, language)
  const inspect = page.getByRole('button', { name: ar ? 'فحص طلب التصحيح' : 'Inspect correction request', exact: true })
  await expect(inspect).toBeDisabled()
  await page.getByRole('checkbox', { name: ar ? 'مبلغ التمويل' : 'Financing amount', exact: true }).check()
  const amountReason = page.getByRole('textbox', { name: ar ? 'سبب التصحيح: مبلغ التمويل' : 'Correction reason: Financing amount', exact: true })
  await expect(inspect).toBeDisabled()
  await amountReason.fill(ar ? 'خفّض المبلغ المطلوب.' : 'Reduce the requested amount.')
  await page.getByRole('checkbox', { name: ar ? 'عرض سعر المعدات' : 'Supplier quotation', exact: true }).check()
  await page.getByRole('textbox', { name: ar ? 'سبب التصحيح: عرض سعر المعدات' : 'Correction reason: Supplier quotation', exact: true }).fill(ar ? 'أضف عرض سعر مقروءًا.' : 'Supply a readable quotation.')
  await expect(page.getByRole('checkbox', { name: ar ? 'تكلفة الشراء' : 'Purchase budget', exact: true })).not.toBeChecked()
  await inspect.focus(); await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: ar ? 'تأكيد طلب التصحيح' : 'Confirm correction request', exact: true })
  await expect(dialog).toContainText(ar ? 'خفّض المبلغ المطلوب.' : 'Reduce the requested amount.')
  await expect(dialog).toContainText('RIFD-2026-007')
  await expect(dialog.getByRole('listitem')).toHaveCount(2)
  await page.keyboard.press('Escape'); await expect(inspect).toBeFocused()
  await expect(amountReason).toHaveValue(ar ? 'خفّض المبلغ المطلوب.' : 'Reduce the requested amount.')
  await inspect.click()
  await dialog.getByRole('button', { name: ar ? 'تأكيد وإرسال الطلب' : 'Confirm and send request', exact: true }).click()
  await expect(page.getByRole('region', { name: ar ? 'طلب تصحيحات' : 'Request corrections', exact: true }).getByRole('status')).toContainText(ar ? 'أُرسل طلب التصحيح.' : 'Correction request sent.')
  await page.getByRole('link', { name: ar ? 'العودة إلى المراجعة' : 'Back to review', exact: true }).click()
  await expect(page.getByRole('button', { name: ar ? 'قبول المستند' : 'Accept document', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: ar ? 'حفظ الملاحظة' : 'Save note', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: ar ? 'طلب تصحيحات' : 'Request corrections', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: ar ? 'تغيير الهوية' : 'Switch identity', exact: true }).click()
  await page.getByRole('button', { name: ar ? 'مريم سالم' : 'Mariam Salem', exact: true }).click()
  await expect(page).toHaveURL(/\/applications$/)
  await page.goto('/applications/RIFD-2026-007/history')
  await expect(page.getByText(ar ? 'خفّض المبلغ المطلوب.' : 'Reduce the requested amount.', { exact: true }).first()).toBeVisible()
  await expect(page.getByText(ar ? 'أضف عرض سعر مقروءًا.' : 'Supply a readable quotation.', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('heading', { name: ar ? 'ملاحظات داخلية' : 'Internal notes', exact: true })).toHaveCount(0)
})

test('unsent reasons survive language changes, stay and expiry, and departure never sends', async ({ page }) => {
  await start(page)
  await page.getByRole('checkbox', { name: 'Financing amount', exact: true }).check()
  const reason = page.getByRole('textbox', { name: 'Correction reason: Financing amount', exact: true })
  await reason.fill('Keep this unsent explanation.')
  await page.getByRole('button', { name: 'العربية', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'سبب التصحيح: مبلغ التمويل', exact: true })).toHaveValue('Keep this unsent explanation.')
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await page.getByRole('link', { name: 'Back to review', exact: true }).click()
  const leave = page.getByRole('dialog', { name: 'You have unsaved work', exact: true })
  await expect(leave.getByRole('button', { name: /Save|Send/ })).toHaveCount(0)
  await leave.getByRole('button', { name: 'Stay', exact: true }).click()
  await expect(reason).toHaveValue('Keep this unsent explanation.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Return to editing', exact: true }).click()
  await page.getByRole('button', { name: 'Expire session', exact: true }).click()
  await expect(reason).toHaveCount(0)
  await page.getByRole('button', { name: 'Huda Ali', exact: true }).click()
  await expect(leave).toBeVisible()
  await leave.getByRole('button', { name: 'Stay', exact: true }).click()
  await page.getByRole('button', { name: 'Salma Nasser', exact: true }).click()
  await expect(reason).toHaveValue('Keep this unsent explanation.')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link', { name: 'Back to review', exact: true }).click()
  await leave.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page).toHaveURL(/\/RIFD-2026-007$/)
  await expect(page.getByRole('button', { name: 'Accept document', exact: true }).first()).toBeVisible()
  await page.getByRole('link', { name: 'Request corrections', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Financing amount', exact: true })).not.toBeChecked()
})

test('a failed send retains reasons and requires inspection and a fresh confirmation', async ({ page }) => {
  await start(page)
  await page.getByRole('checkbox', { name: 'Financing amount', exact: true }).check()
  const reason = page.getByRole('textbox', { name: 'Correction reason: Financing amount', exact: true })
  await reason.fill('Retain after the write aborts.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args: Parameters<IDBObjectStore['put']>) {
      IDBObjectStore.prototype.put = put
      const request = put.apply(this, args)
      request.addEventListener('success', () => this.transaction.abort(), { once: true })
      return request
    }
  })
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and send request', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(reason).toHaveValue('Retain after the write aborts.')
  await expect(page.getByRole('button', { name: 'Inspect correction request', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Inspect correction request outcome', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Request corrections', exact: true }).getByRole('status')).toContainText('The request was not sent.')
  await reason.fill('A revised explanation needs fresh confirmation.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('A revised explanation needs fresh confirmation.')
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and send request', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Request corrections', exact: true }).getByRole('status')).toContainText('Correction request sent.')
})

test('unknown completion is inspected before retry and shows one request', async ({ page }) => {
  await start(page)
  await page.getByRole('checkbox', { name: 'Mobile', exact: true }).check()
  await page.getByRole('textbox', { name: 'Correction reason: Mobile', exact: true }).fill('Correct the contact number.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  await page.evaluate(loseNextWriteCompletion)
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and send request', exact: true }).click()
  const inspect = page.getByRole('button', { name: 'Inspect correction request outcome', exact: true })
  await expect(inspect).toBeVisible({ timeout: 15_000 })
  await expect(page.getByRole('button', { name: 'Inspect correction request', exact: true })).toBeDisabled()
  await inspect.click()
  await expect(page.getByRole('region', { name: 'Request corrections', exact: true }).getByRole('status')).toContainText('Correction request sent.')
  await expect(page.getByText('Correct the contact number.', { exact: true })).toHaveCount(1)
})

test('reassignment closes confirmation and retains the unsent request as read-only', async ({ page, context }) => {
  await start(page)
  await page.getByRole('checkbox', { name: 'Financing amount', exact: true }).check()
  const reason = page.getByRole('textbox', { name: 'Correction reason: Financing amount', exact: true })
  await reason.fill('Preserve through transfer.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  const second = await context.newPage()
  await start(second, 'en', '007', false)
  await second.getByRole('button', { name: 'Transfer to Khaled Ali', exact: true }).click()
  await second.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(reason).toHaveValue('Preserve through transfer.')
  await expect(reason).toHaveAttribute('readonly')
  await expect(page.getByRole('button', { name: 'Inspect correction request', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Inspect latest application', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Inspect correction request', exact: true })).toBeDisabled()
  await expect(page.getByText('Khaled Ali', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reclaim from Khaled Ali', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Inspect latest application', exact: true }).click()
  await expect(reason).toHaveValue('Preserve through transfer.')
  await page.getByRole('button', { name: 'Inspect correction request', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and send request', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Request corrections', exact: true }).getByRole('status')).toContainText('Correction request sent.')
})
