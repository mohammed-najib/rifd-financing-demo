import { expect, test } from '@playwright/test'
import { nativeIdentity } from './evidence-transport'

test('the draft screen runs a fixed check through fake HTTP and preserves results across language changes', async ({ page }, info) => {
  const requests: { authorization: string | undefined; body: Record<string, unknown> }[] = []
  await page.route('**/fake-provider/systemone', async route => {
    requests.push({ authorization: route.request().headers().authorization, body: route.request().postDataJSON() })
    await route.fulfill({ json: nativeIdentity() })
  })
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('/tests/browser/evidence-screen.html')
  await page.getByRole('button', { name: 'فحص المستند', exact: true }).click()
  let assistance = page.getByRole('region', { name: 'مساعدة تجريبية', exact: true })
  await expect(assistance.getByRole('button', { name: 'بدء الفحص', exact: true })).toBeEnabled()
  expect(requests).toHaveLength(0)
  await assistance.getByRole('button', { name: 'بدء الفحص', exact: true }).focus(); await page.keyboard.press('Enter')
  await expect(assistance.getByText('يبدو الاسم المطبوع مختلفًا عن الاسم المعلن', { exact: true })).toBeVisible()
  await expect(assistance.getByText('يبدو أن اسم المتقدم مطبوع', { exact: true })).toBeVisible()
  await assistance.getByRole('button', { name: 'عرض المصدر الحالي', exact: true }).click()
  await expect(assistance.getByRole('img')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await assistance.screenshot({ path: info.outputPath('identity-ar-390.png') })
  await page.getByRole('button', { name: 'English', exact: true }).click()
  assistance = page.getByRole('region', { name: 'Experimental assistance', exact: true })
  await expect(assistance.getByText('Printed name appears different from the declared name', { exact: true })).toBeVisible()
  expect(requests).toHaveLength(1)
  expect(await assistance.innerText()).not.toContain('jev-1.14.0')
  await assistance.getByText('Analysis provenance', { exact: true }).click()
  await expect(assistance.locator('pre')).toContainText('provisional-display-defaults-v1')
  await expect(assistance.locator('pre')).toContainText('1.995')
  expect(requests[0].authorization).toBe('Bearer dummy-test-key')
  expect(requests[0].body).toMatchObject({ stage: 'combined-page-declaration', plan: { maximumAttempts: 2 }, state: { page: 'original-page-1' }, image: { totalPages: 1, manifest: { width: 1000, height: 1320 } } })
  expect((requests[0].body.image as { bytes: number[] }).bytes.slice(0, 8)).toEqual([137, 80, 78, 71, 13, 10, 26, 10])
  await assistance.getByRole('button', { name: 'Retain document', exact: true }).click()
  await expect(assistance.getByText('You can retain this document. Use the ordinary Save action for any edits.', { exact: true })).toBeVisible()
  await assistance.screenshot({ path: info.outputPath('identity-en-390.png') })
  await assistance.getByRole('button', { name: 'Edit declared name', exact: true }).click()
  await page.getByRole('textbox', { name: 'Applicant full name', exact: true }).fill('Changed Fictional Name')
  await page.locator('a[href="?step=documents"]').click()
  await expect(page.getByRole('button', { name: 'Check document', exact: true })).toBeVisible()
  expect(requests).toHaveLength(1)
})
