test('departure never sends the reason and a storage abort needs fresh inspection and confirmation', async ({ page }) => {
  await start(page); await failPurpose(page)
  const reason = page.getByRole('textbox', { name: 'Applicant-visible decision reason', exact: true })
  await reason.fill('Keep this explanation until I confirm.')
  await page.getByRole('link', { name: 'Back to review', exact: true }).click()
  const leave = page.getByRole('dialog', { name: 'You have unsaved work', exact: true })
  await expect(leave.getByRole('button', { name: /Save|Send/ })).toHaveCount(0)
  await leave.getByRole('button', { name: 'Stay', exact: true }).click()
  await expect(reason).toHaveValue('Keep this explanation until I confirm.')
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args: Parameters<IDBObjectStore['put']>) {
      IDBObjectStore.prototype.put = put
      const request = put.apply(this, args)
      request.addEventListener('success', () => this.transaction.abort(), { once: true })
      return request
    }
  })
  await page.getByRole('button', { name: 'Inspect rejection', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm final decision', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(reason).toHaveValue('Keep this explanation until I confirm.')
  await page.getByRole('button', { name: 'Inspect decision outcome', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'The decision was not saved.' })).toBeVisible()
  await page.getByRole('button', { name: 'Inspect rejection', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Keep this explanation until I confirm.')
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm final decision', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Final decision saved.' })).toBeVisible()
})
