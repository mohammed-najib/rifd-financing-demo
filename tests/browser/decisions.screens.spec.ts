test('expiry and reassignment invalidate confirmation while retaining the unsent reason', async ({ page, context }) => {
  await page.clock.install()
  await start(page); await failPurpose(page)
  const reason = page.getByRole('textbox', { name: 'Applicant-visible decision reason', exact: true })
  await reason.fill('Retain my explanation through recovery.')
  await page.getByRole('button', { name: 'Inspect rejection', exact: true }).click()
  await page.clock.fastForward(16 * 60 * 1000)
  await page.getByRole('button', { name: 'Salma Nasser', exact: true }).click()
  await expect(reason).toHaveValue('Retain my explanation through recovery.')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Inspect rejection', exact: true }).click()
  const other = await context.newPage()
  await other.goto('/staff/applications/RIFD-2026-007')
  await expect(other.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 30_000 })
  await other.getByRole('button', { name: 'Salma Nasser', exact: true }).click()
  await other.getByRole('button', { name: 'Transfer to Khaled Ali', exact: true }).click()
  await other.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(reason).toHaveValue('Retain my explanation through recovery.')
  await expect(reason).toHaveAttribute('readonly')
  await page.getByRole('button', { name: 'Inspect latest application', exact: true }).click()
  await page.getByRole('button', { name: 'Reclaim from Khaled Ali', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await page.getByRole('button', { name: 'Inspect latest application', exact: true }).click()
  await page.getByRole('button', { name: 'Inspect rejection', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Retain my explanation through recovery.')
})

test('unknown completion is inspected and cannot send another final decision', async ({ page }) => {
  await start(page); await failPurpose(page)
  await page.getByRole('textbox', { name: 'Applicant-visible decision reason', exact: true }).fill('An independent substantive criterion failed.')
  await page.getByRole('button', { name: 'Inspect rejection', exact: true }).click()
  await page.evaluate(loseNextWriteCompletion)
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm final decision', exact: true }).click()
  const inspect = page.getByRole('button', { name: 'Inspect decision outcome', exact: true })
  await expect(inspect).toBeVisible({ timeout: 20_000 })
  await expect(page.getByRole('button', { name: 'Inspect rejection', exact: true })).toBeDisabled()
  await inspect.click()
  await expect(page.getByRole('status').filter({ hasText: 'Final decision saved.' })).toBeVisible()
  await expect(page.getByText('An independent substantive criterion failed.', { exact: true })).toHaveCount(1)
})

