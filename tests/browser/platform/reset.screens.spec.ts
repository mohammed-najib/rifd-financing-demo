test.describe.configure({ mode: 'parallel' })

test('uncertain reset offers outcome inspection before another confirmation', async ({ page }) => {
  await page.goto('/demo/reset')
  await expect(page.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'English', exact: true }).click()
  await page.getByRole('button', { name: 'Reset demo', exact: true }).last().click()
  await page.evaluate(loseNextWriteCompletion)
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Replace all demo data', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Inspect reset outcome', exact: true })).toBeVisible({ timeout: 60_000 })
  await expect(dialog.getByRole('button', { name: 'Replace all demo data', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Inspect reset outcome', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'اختر هوية تجريبية', exact: true })).toBeVisible({ timeout: 30_000 })
})

test('another tab observes success, closes its preview and discards its old unfinished work', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: 'English', exact: true }).click()
  const other = await context.newPage()
  await other.addInitScript(() => { Object.defineProperty(window, 'BroadcastChannel', { value: class { constructor() { throw new Error('Missed reset hint') } } }) })
  await other.goto('/applications/RIFD-2026-001/edit?step=financing')
  await expect(other.locator('[data-workspace-ready="true"]')).toBeVisible({ timeout: 30_000 })
  await other.getByRole('button', { name: 'Mariam Salem', exact: true }).click()
  await other.getByLabel('Purchase explanation', { exact: true }).fill('Old tab unfinished work')
  await other.locator('a[href="?step=documents"]').click()
  const purchase = other.getByRole('heading', { name: 'Stock purchase plan', exact: true }).first().locator('..')
  await purchase.getByRole('button', { name: 'Preview saved file', exact: true }).click()
  await expect(other.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('button', { name: 'Replace all demo data', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'اختر هوية تجريبية', exact: true })).toBeVisible({ timeout: 30_000 })
  await other.evaluate(() => { for (let index = 0; index < 3; index++) window.dispatchEvent(new Event('focus')) })
  await expect(other.getByRole('heading', { name: 'اختر هوية تجريبية', exact: true })).toBeVisible({ timeout: 30_000 })
  await expect(other.getByRole('dialog')).toHaveCount(0)
  await other.getByRole('button', { name: 'مريم سالم', exact: true }).click()
  await other.getByRole('link', { name: 'الاطلاع على المسودة المحفوظة', exact: true }).click()
  await other.locator('a[href="?step=financing"]').click()
  await expect(other.getByLabel('شرح الشراء', { exact: true })).toHaveValue('')
})

